    rect(x, y, w, h, fill, stroke)
    text(x + 10, y + 19, title, size=tsize, weight="700", fill="#1f2933", maxw=w - 16)
    for i, ln in enumerate(lines):
        mono = ln.startswith("`")
        s = ln.strip("`")
        text(x + 10, y + 36 + i * lh, s, size=size, mono=mono, maxw=w - 16)
    return h


