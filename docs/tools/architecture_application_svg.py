"""
Generates docs/architecture-application.svg, the application-level
companion to the hand-maintained docs/architecture.svg (same colours and
fonts). The module map is the `rows` list below: add a row there for a new
module and re-run, rather than shifting every SVG element below it by hand.

Usage (from the repo root, no dependencies beyond the standard library):
    python3 docs/tools/architecture_application_svg.py [output.svg]

Text widths are only estimated; a line that probably overflows its box is
reported as a warning on stderr. Check the result in a browser.
"""
